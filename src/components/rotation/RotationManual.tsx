export default function RotationManual({ open, onOpenChange }: { open: boolean; onOpenChange: (v: boolean) => void }) {
  const [query, setQuery] = useState("");
  const [active, setActive] = useState("start");

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return SECTIONS;
    return SECTIONS.filter((s) => [s.title, s.intro, s.warn, ...(s.steps || []), ...(s.tips || [])].join(" ").toLowerCase().includes(q));
  }, [query]);

  const go = (id: string) => {
    setActive(id);
    document.getElementById(`man-${id}`)?.scrollIntoView({ behavior: "smooth", block: "start" });
  };

  const print = () => {
    const w = window.open("", "_blank", "width=900,height=800");
    if (!w) return;
    const html = SECTIONS.map(
      (s) =>
        `<h2>${s.title}</h2>${s.intro ? `<p>${s.intro}</p>` : ""}${s.steps ? `<ol>${s.steps.map((x) => `<li>${x}</li>`).join("")}</ol>` : ""}${
          s.tips ? `<ul class="tip">${s.tips.map((x) => `<li>${x}</li>`).join("")}</ul>` : ""
        }${s.warn ? `<p class="warn">${s.warn}</p>` : ""}`
    ).join("");
    w.document.write(`<html><head><title>Инструкция — Перевахтовка</title><style>body{font-family:Arial;padding:24px;max-width:820px;margin:auto;line-height:1.5}h1{margin-top:0}h2{margin-top:28px;border-bottom:1px solid #ccc;padding-bottom:4px}li{margin:4px 0}.tip li{color:#0b6b7a}.warn{color:#a35a00}.bar{margin-bottom:16px}@media print{.bar{display:none}}</style></head><body><div class="bar"><button onclick="window.print()" style="padding:8px 18px;font-size:14px">Печать</button></div><h1>Инструкция: раздел «Перевахтовка»</h1>${html}</body></html>`);
    w.document.close();
  };

  return (
    <Sheet open={open} onOpenChange={onOpenChange}>
      <SheetContent side="right" className="w-full sm:max-w-3xl p-0 flex flex-col">
        <SheetHeader className="px-6 pt-6 pb-4 border-b border-border space-y-3">
          <div className="flex items-center gap-3 pr-8">
            <div className="w-10 h-10 rounded-lg bg-primary/10 flex items-center justify-center">
              <Icon name="BookOpenCheck" size={20} className="text-primary" fallback="BookOpen" />
            </div>
            <div className="flex-1">
              <SheetTitle>Инструкция: Перевахтовка</SheetTitle>
              <SheetDescription>Пошагово — от настройки подразделений до контроля заезда на КПП</SheetDescription>
            </div>
            <button onClick={print} className="flex items-center gap-1.5 rounded-lg border border-border px-3 py-1.5 text-xs text-foreground hover:bg-secondary">
              <Icon name="Printer" size={14} />
              Печать
            </button>
          </div>
          <div className="relative">
            <Icon name="Search" size={14} className="absolute left-3 top-1/2 -translate-y-1/2 text-muted-foreground" />
            <Input value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Поиск по инструкции: «отпуск», «Excel», «КПП»…" className="pl-9" />
          </div>
        </SheetHeader>

        <div className="flex-1 min-h-0 flex">
          <nav className="hidden md:block w-56 shrink-0 border-r border-border overflow-y-auto py-3">
            {filtered.map((s) => (
              <button
                key={s.id}
                onClick={() => go(s.id)}
                className={`w-full flex items-center gap-2 px-4 py-2 text-left text-sm ${
                  active === s.id ? "text-primary bg-primary/10 font-medium" : "text-muted-foreground hover:text-foreground"
                }`}
              >
                <Icon name={s.icon} size={14} fallback="Circle" />
                <span className="truncate">{s.title}</span>
              </button>
            ))}
          </nav>

          <div className="flex-1 overflow-y-auto px-6 py-5 space-y-8">
            {filtered.length === 0 && <p className="text-sm text-muted-foreground text-center py-10">Ничего не найдено</p>}
            {filtered.map((s) => (
              <section key={s.id} id={`man-${s.id}`} className="scroll-mt-4">
                <h3 className="text-base font-semibold text-foreground flex items-center gap-2">
                  <Icon name={s.icon} size={18} className="text-primary" fallback="Circle" />
                  {s.title}
                </h3>
                {s.intro && <p className="text-sm text-muted-foreground mt-2">{s.intro}</p>}
                {s.steps && (
                  <ol className="mt-3 space-y-2">
                    {s.steps.map((st, i) => (
                      <li key={i} className="flex gap-3 text-sm text-foreground">
                        <span className="shrink-0 w-6 h-6 rounded-full bg-secondary text-xs font-semibold flex items-center justify-center text-muted-foreground">{i + 1}</span>
                        <span className="pt-0.5">{st}</span>
                      </li>
                    ))}
                  </ol>
                )}
                {s.tips && (
                  <div className="mt-3 rounded-lg border border-mine-cyan/30 bg-mine-cyan/5 p-3 space-y-1.5">
                    {s.tips.map((t, i) => (
                      <p key={i} className="text-sm text-foreground flex gap-2">
                        <Icon name="Lightbulb" size={14} className="text-mine-cyan shrink-0 mt-0.5" />
                        {t}
                      </p>
                    ))}
                  </div>
                )}
                {s.warn && (
                  <p className="mt-3 rounded-lg border border-mine-amber/30 bg-mine-amber/5 p-3 text-sm text-foreground flex gap-2">
                    <Icon name="AlertTriangle" size={14} className="text-mine-amber shrink-0 mt-0.5" />
                    {s.warn}
                  </p>
                )}
              </section>
            ))}
          </div>
        </div>
      </SheetContent>
    </Sheet>
  );
}
